"""A file that declares itself generated is recognised, and a file that merely mentions it is not.

WHY. Generated code — API clients, protobuf stubs, generated test data — can make up most of a
repository's symbols and crowd hand-written code out of search. clew already recognises one kind
of generated file, an output named by a CMake rule. A file whose generator ran OUTSIDE the build
announces itself only through its own banner, so the banner is what is read.

EVERY BANNER BELOW IS VERBATIM from the generator's template or from its real output, not
paraphrased: OpenAPI Generator, swagger-typescript-api, orval, Apollo, Relay, ts-proto,
protoc-gen-es, Prisma and openapi-typescript. Guessing the wording would have missed OpenAPI
Generator outright — it writes "auto generated", with a space.

PRECISION WAS MEASURED BEFORE THIS WAS WRITTEN, on ~10,000 tracked files across mbedtls, entropic,
clew itself and mattermost-mobile. The first rule set flagged the GENERATOR SCRIPTS — which carry
the banner they write, inside a string, around line 25 — plus a docstring and a `.in` template.
The generic rule therefore requires a COMMENT in the FIRST FIVE LINES, and a `.in` file is a
template, never an output. After that: 23 flagged, zero false positives. Each false positive
measured is pinned below as a miss.

@brief Tests for self-declared generated-file detection.
@version 1
"""

from __future__ import annotations

import pytest

from clew.generated import self_declared

## Verbatim banners, each from its generator's own template or real output.
_GENERATED = {
    "openapi-generator": (
        "api.ts",
        "/* tslint:disable */\n/* eslint-disable */\n/**\n * Petstore\n"
        " * NOTE: This class is auto generated by OpenAPI Generator "
        "(https://openapi-generator.tech).\n * Do not edit the class manually.\n */\n",
    ),
    "swagger-typescript-api": (
        "Api.ts",
        "/* eslint-disable */\n/* tslint:disable */\n// @ts-nocheck\n/*\n"
        " * ---------------------------------------------------------------\n"
        " * ## THIS FILE WAS GENERATED VIA SWAGGER-TYPESCRIPT-API        ##\n */\n",
    ),
    "orval": ("pet.ts", "/**\n * Generated by orval 🍺\n * Do not edit manually.\n */\n"),
    "apollo": (
        "types.ts",
        "/* tslint:disable */\n/* eslint-disable */\n// @generated\n"
        "// This file was automatically generated and should not be edited.\n",
    ),
    "relay": (
        "AppQuery.graphql.js",
        "/**\n * Copyright (c) Meta Platforms, Inc. and affiliates.\n *\n * x\n *\n"
        " * @generated SignedSource<<5213156639f5e33acfdd79872ea56f77>>\n */\n",
    ),
    "ts-proto": (
        "encode.ts",
        "// Code generated by protoc-gen-ts_proto. DO NOT EDIT.\n// source: encode.proto\n",
    ),
    "protoc-gen-es": (
        "msg_pb.ts",
        '// @generated by protoc-gen-es v2.16.0 with parameter "target=ts"\n',
    ),
    "prisma": (
        "client.ts",
        "/* !!! This is code generated by Prisma. Do not edit directly. !!! */\n/* eslint-disable */\n",
    ),
    "openapi-typescript": (
        "schema.ts",
        "/**\n * This file was auto-generated by openapi-typescript.\n"
        " * Do not make direct changes to the file.\n */\n",
    ),
    "make, found in mattermost-mobile": (
        "app/utils/emoji/index.ts",
        "// This file is automatically generated via `make emojis`. Do not modify it manually.\n",
    ),
    "python generator, found in mbedtls": (
        "library/ssl_debug_helpers_generated.c",
        "/* Automatically generated by generate_ssl_debug_helpers.py. DO NOT EDIT. */\n",
    ),
}

## Every false positive the precision measurement found, plus the noise the research warned of.
_NOT_GENERATED = {
    "a generator script, banner in its template at line 25": (
        "scripts/generate_psa_constants.py",
        "".join(f"# line {i}\n" for i in range(24))
        + "/* Automatically generated by generate_psa_constant.py. DO NOT EDIT. */\n",
    ),
    "prose in a docstring that names the marker": (
        "tests/test_x.py",
        '"""Tests.\n\nThe marker that identifies it (`AUTO-GENERATED`, `do not edit`) also '
        'matches.\n"""\n',
    ),
    "a .in template whose OUTPUT is generated": (
        "include/config.h.in",
        "/**\n * @file\n * @brief Generated build configuration — DO NOT EDIT.\n */\n",
    ),
    "a bare DO NOT EDIT in a config comment": (
        "settings.ts",
        "// DO NOT EDIT these defaults without updating the docs.\nexport const x = 1;\n",
    ),
    "lint suppressions alone": ("legacy.ts", "/* eslint-disable */\n// @ts-nocheck\nexport {};\n"),
    "an ordinary module": (
        "util.ts",
        "export function add(a: number, b: number) { return a + b; }\n",
    ),
}


@pytest.mark.parametrize("label", sorted(_GENERATED))
def test_a_self_declared_generated_file_is_recognised(label: str) -> None:
    """@brief Each verbatim banner is recognised.
    @version 1
    """
    path, text = _GENERATED[label]
    assert self_declared(path, text.encode("utf-8")) is not None, label


@pytest.mark.parametrize("label", sorted(_NOT_GENERATED))
def test_a_file_that_only_mentions_generation_is_not(label: str) -> None:
    """@brief Each measured false positive stays a miss.
    @version 1
    """
    path, text = _NOT_GENERATED[label]
    assert self_declared(path, text.encode("utf-8")) is None, label


@pytest.mark.parametrize(
    "path",
    [
        "src/__generated__/AppQuery.graphql.ts",
        "gen/user_pb.ts",
        "src/api/client.generated.ts",
        "src/queries/Profile.graphql.js",
    ],
)
def test_a_generated_path_convention_is_recognised(path: str) -> None:
    """THE PATH IS A SECOND, INDEPENDENT SIGNAL, from GitHub linguist's curated rules
    (`__generated__/`) plus the protobuf and codegen suffix conventions. It needs no banner, so it
    still holds when a generator's banner has been switched off.

    @brief Conventional generated paths are recognised without a banner.
    @version 1
    """
    assert self_declared(path, b"export const x = 1;\n") is not None, path


def test_the_evidence_names_what_matched() -> None:
    """THE EVIDENCE IS SERVED, so a reader can check the call. "generated" with no reason is a
    claim; "generated: `@generated` banner" is a claim with its proof.

    @brief Evidence says why.
    @version 1
    """
    path, text = _GENERATED["apollo"]
    evidence = self_declared(path, text.encode("utf-8"))
    assert evidence and "@generated" in evidence, evidence
