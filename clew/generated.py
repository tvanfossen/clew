"""WHICH FILES DECLARE THEMSELVES GENERATED, read from the file rather than from a build rule.

clew already knows one kind of generated file: an output a CMake `add_custom_command` names
(`synth.generated_files`). A generator that runs OUTSIDE the build — an OpenAPI client, a protobuf
stub, generated test data checked into the tree — leaves no rule to read. What it does leave is a
banner, because every mainstream generator writes one so humans do not edit its output. That banner
is the signal here, with a path convention as a second, independent one.

THE PATTERNS ARE VERBATIM, NOT GUESSED. Each was taken from its generator's own template or real
output: OpenAPI Generator, swagger-typescript-api, orval, Apollo, Relay, ts-proto, protoc-gen-es,
Prisma, openapi-typescript. A guessed pattern would have missed OpenAPI Generator outright: it
writes "auto generated", with a space, where a guess writes "auto-generated".

PRECISION WAS MEASURED FIRST, and it reshaped the generic rule. On ~10,000 tracked files across
mbedtls, entropic, clew and mattermost-mobile, "a 'generated' word and 'do not edit' on one line"
flagged the GENERATOR SCRIPTS themselves — they carry the banner they write, inside a template
string near line 25 — plus a docstring that discussed the marker and a `.in` template whose
OUTPUT is generated. Every real output carried its banner as a COMMENT on lines 1-3. So the generic
rule needs a comment in the first five lines and skips `.in`; the specific patterns, which no
hand-written file plausibly contains, keep the wider window, because Relay puts `@generated` on
line 6 behind a licence block. After that: 23 flagged, zero false positives.

DELIBERATELY NOT SIGNALS, as the research warned and the measurement agreed: a bare "DO NOT EDIT"
(hand-written config comments say it), a bare "auto-generated", and lint suppressions such as
`/* eslint-disable */`, which hand-written files use constantly.

@brief Recognise self-declared generated files.
@version 1
"""

from __future__ import annotations

import re
import sqlite3
from pathlib import Path

from .indexcache import IndexCache, memoized

## How much of a file is read. A banner is at the top; reading further only adds the chance of
## matching the TEMPLATE a generator script carries for its output.
HEAD_BYTES = 2048
## The memoized payload's version: bump when `self_declared`'s patterns change.
SELF_DECLARED_STAGE_VERSION = 1

## The generic rule's window. Every real banner measured sat on lines 1-3; generator scripts carried
## theirs near line 25, so five is generous and still excludes them.
GENERIC_LINES = 5

## Generator-specific banners, each low-risk because no hand-written file plausibly says it.
_SPECIFIC: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("`@generated` banner", re.compile(r"@generated\b", re.I)),
    (
        "`Code generated by ... DO NOT EDIT` banner",
        re.compile(r"code generated by[^\n]*do not edit", re.I),
    ),
    ("OpenAPI Generator banner", re.compile(r"auto[- ]?generated by openapi generator", re.I)),
    ("openapi-typescript banner", re.compile(r"auto[- ]?generated by openapi-typescript", re.I)),
    ("orval banner", re.compile(r"generated by orval", re.I)),
    ("swagger-typescript-api banner", re.compile(r"generated via swagger-typescript-api", re.I)),
    ("Prisma banner", re.compile(r"code generated by prisma", re.I)),
    ("Apollo banner", re.compile(r"automatically generated and should not be edited", re.I)),
    (
        "protobuf banner",
        re.compile(r"generated by (?:the protocol buffer compiler|protoc-gen-)", re.I),
    ),
)

## A comment line that says it was generated AND tells the reader not to edit it. Comment-anchored
## and confined to the first lines, for the reason this module's docstring gives.
_GENERIC = re.compile(
    r"^\s*(?://|/\*|\*|#|--)[^\n]*generated[^\n]*\bdo not (?:edit|modify|change)\b", re.I
)

## Path conventions: linguist's `__generated__/` (Relay), and the suffixes generators name their
## outputs with. NOT `codegen/` or `gen/` directories — those usually hold the generator's own
## scripts, which is the false positive this module exists to avoid.
_PATH = re.compile(
    r"(?:^|/)__generated__/"
    r"|\.graphql\.[cm]?[jt]sx?$"
    r"|_pb\.[cm]?[jt]sx?$"
    r"|\.generated\.[cm]?[jt]sx?$"
)

## Template sources: their banner describes the file generated FROM them, not themselves.
_TEMPLATE_SUFFIXES = (".in",)


## @brief The evidence that a file declares itself generated, or None.
## @param rel_path Repository-relative POSIX path.
## @param head The file's first bytes; at most `HEAD_BYTES` are read.
## @return A short description of what matched, or None.
## @version 1
## @utility
def self_declared(rel_path: str, head: bytes) -> str | None:
    """EVIDENCE, NOT A BOOLEAN, because it is served: "generated" alone is a claim, "generated:
    `@generated` banner" is a claim a reader can check. The path convention is tried first since
    it needs no read and holds even where a generator's banner has been switched off.

    @brief Name why a file is generated.
    @return Evidence, or None.
    @version 1
    """
    match = _PATH.search(rel_path)
    if match:
        return f"path convention `{match.group(0).strip('/')}`"
    text = head[:HEAD_BYTES].decode("utf-8", errors="replace")
    for label, pattern in _SPECIFIC:
        if pattern.search(text):
            return label
    if rel_path.endswith(_TEMPLATE_SUFFIXES):
        return None
    if any(_GENERIC.search(line) for line in text.splitlines()[:GENERIC_LINES]):
        return "banner: generated, do not edit"
    return None


## The `generated_files.kind` prefix for a file that declares itself generated. Its evidence
## follows, as in "self-declared: `@generated` banner", so the served record says why.
KIND_SELF_DECLARED = "self-declared"


## @brief Record every indexed file that declares itself generated.
## @param db_path The database under construction.
## @param repo_root Repository root the indexed paths are relative to.
## @param cache The run's index cache, or None for an uncached build.
## @return Number of files recorded.
## v2 (1.3.4): an unchanged file's evidence is served from the index cache.
## @version 2
## @utility
def record_self_declared(db_path: Path, repo_root: Path, cache: IndexCache | None = None) -> int:
    """EVERY INDEXED FILE, NOT ONLY JS/TS. Generated code is not a JavaScript phenomenon: mbedtls
    commits nineteen generated files, from `*_generated.c` to its test-data suites. This runs as its
    own step for that reason — the parse front end returns early on a repository with no JS/TS or
    script file, and a scan placed inside it would never see a C tree at all.

    ONE ROW PER FILE, keyed by the EXACT path in `output_literal`. `generated_files` is otherwise
    joined on basename, and a banner row joined that way would mark every same-named file generated
    — `index.ts` most of all. The reader matches these rows on the exact path for that reason.

    `source_line` is 0, meaning not applicable: the evidence is the file's own header, and
    `source_file` names the file itself.

    @brief Write the self-declared generated files.
    @return Files recorded.
    @version 1
    """
    from .synth import ensure_generated_files_table

    conn = sqlite3.connect(str(db_path))
    try:
        ensure_generated_files_table(conn)
        rows = []
        for (name,) in conn.execute("SELECT name FROM path WHERE type = 1").fetchall():
            rel = str(name)
            ## MEMOIZED ON THE FILE'S CONTENT AND PATH (1.3.4): the banner regexes over every
            ## file's head were the cost, and the path convention is part of the answer.
            evidence = memoized(
                cache,
                rel,
                repo_root / rel,
                "self_declared",
                SELF_DECLARED_STAGE_VERSION,
                rel,
                lambda rel=rel: _evidence_of(repo_root / rel, rel),
            )
            if evidence:
                rows.append(
                    (rel, rel, f"{KIND_SELF_DECLARED}: {evidence}", rel, 0, "output", "", "")
                )
        conn.executemany(
            "INSERT INTO generated_files (output_name, output_literal, kind, source_file, "
            "source_line, role, arg_name, arg_literal) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            rows,
        )
        conn.commit()
    finally:
        conn.close()
    return len(rows)


## @brief The exact paths of every self-declared generated file in an index.
## @param conn Open index connection.
## @return The paths; empty when there are none or the table is absent.
## @version 1
## @utility
def self_declared_paths(conn: sqlite3.Connection) -> frozenset[str]:
    """@brief Read the self-declared generated paths.
    @return Paths.
    @version 1
    """
    present = conn.execute(
        "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'generated_files'"
    ).fetchone()
    if not present:
        return frozenset()
    return frozenset(
        str(r[0])
        for r in conn.execute(
            "SELECT output_literal FROM generated_files WHERE kind LIKE ?",
            (f"{KIND_SELF_DECLARED}:%",),
        )
    )


## @brief One file's generated-code evidence, read from its head.
## @param path The file.
## @param rel Its repo-relative path.
## @return The evidence, or None when unreadable or not generated.
## @version 1
## @dg_internal
def _evidence_of(path: Path, rel: str) -> str | None:
    """@brief Read the head and test it. @return Evidence or None."""
    try:
        with path.open("rb") as handle:
            head = handle.read(HEAD_BYTES)
    except OSError:
        return None
    return self_declared(rel, head)
